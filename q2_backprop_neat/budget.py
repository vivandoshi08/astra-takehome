"""Gradient-step accounting for Q2.

You get a fixed budget of gradient steps per run — 30,000 by default. How you
spend it is the question: many genomes refined shallowly, fewer refined deeply,
or only the elite refined at all.

    budget = StepBudget()
    ...
    budget.charge(steps)          # once per genome you refine
    budget.remaining()            # steps left

`main.py` derives the generation count from your choices so a run lands inside
the budget. Report `budget.summary()` with every result.

Do not edit this file. If the budget blocks something reasonable, say so in
your report.
"""

from __future__ import annotations

DEFAULT_BUDGET = 30_000


class BudgetExhausted(RuntimeError):
    """Raised when the gradient-step budget is spent."""


class StepBudget:
    def __init__(self, limit: int = DEFAULT_BUDGET):
        self.limit = limit
        self.spent = 0
        self.refinements = 0

    def charge(self, steps: int) -> None:
        self.spent += int(steps)
        self.refinements += 1
        if self.spent > self.limit:
            raise BudgetExhausted(
                f"gradient-step budget exceeded: {self.spent:,} / {self.limit:,}"
            )

    def remaining(self) -> int:
        return max(0, self.limit - self.spent)

    def can_afford(self, steps: int) -> bool:
        return self.spent + steps <= self.limit

    def summary(self) -> str:
        return (f"{self.spent:,}/{self.limit:,} gradient steps over "
                f"{self.refinements:,} refinements")


def plan(pop_size: int, steps_per_genome: int, refine_fraction: float = 1.0,
         limit: int = DEFAULT_BUDGET) -> int:
    """How many generations does this allocation buy?

        plan(100, 10, 1.00) -> 30    # refine everyone, 10 steps each
        plan(100, 20, 1.00) -> 15    # deeper, half as many generations
        plan(100, 40, 0.25) -> 30    # elite-25 only, 40 steps each

    All three cost the same 30,000 steps. They do not perform the same.
    """
    per_gen = max(1, int(round(pop_size * refine_fraction))) * steps_per_genome
    return max(1, limit // per_gen)

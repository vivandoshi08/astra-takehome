"""Token accounting for Q3.

Every model call is counted from the API's own `usage` field — not estimated —
and appended to `token_log.jsonl`. That log is part of your submission.

The cap exists so a runaway loop cannot drain your account. If you hit it,
that is information: note it in your report rather than raising it
silently.

Do not edit this file or the log it writes.
"""

from __future__ import annotations

import json
import time
from pathlib import Path

DEFAULT_CAP = 500_000


class BudgetExhausted(RuntimeError):
    """Raised once the token cap is spent."""


class TokenBudget:
    """Counts real input/output tokens across every call in a run."""

    def __init__(self, limit: int = DEFAULT_CAP,
                 log_path: str | Path | None = "token_log.jsonl"):
        self.limit = limit
        self.log_path = Path(log_path) if log_path else None
        if self.log_path:
            self.log_path.parent.mkdir(parents=True, exist_ok=True)
        self.input_tokens = 0
        self.output_tokens = 0
        self.calls = 0

    @property
    def total_tokens(self) -> int:
        return self.input_tokens + self.output_tokens

    def remaining(self) -> int:
        return max(0, self.limit - self.total_tokens)

    def charge(self, input_tokens: int, output_tokens: int,
               tag: str = "") -> None:
        self.input_tokens += int(input_tokens)
        self.output_tokens += int(output_tokens)
        self.calls += 1
        if self.log_path:
            rec = {
                "call": self.calls,
                "tag": tag,
                "input_tokens": int(input_tokens),
                "output_tokens": int(output_tokens),
                "cumulative": self.total_tokens,
                "wall_ts": time.time(),
            }
            with self.log_path.open("a") as fh:
                fh.write(json.dumps(rec) + "\n")
        if self.total_tokens >= self.limit:
            raise BudgetExhausted(
                f"token cap reached: {self.total_tokens:,} / {self.limit:,} "
                f"after {self.calls} calls"
            )

    def summary(self) -> str:
        return (f"{self.calls} calls, {self.input_tokens:,} in + "
                f"{self.output_tokens:,} out = {self.total_tokens:,} tokens "
                f"({100 * self.total_tokens / self.limit:.0f}% of cap)")

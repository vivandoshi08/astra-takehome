"""Step accounting for Q1.

Every environment step is counted. Counts are flushed periodically to an
append-only log under ``runs/<run-id>/budget_log.jsonl``, which is part of your
submission.

Evolution runs across several worker processes, so each process keeps its own
running count and appends its own records. The driver sums the log at each
generation boundary and stops once the total reaches the limit.

Do not edit this file or the log it writes. If the budget blocks something you
think is reasonable, note it in your report — that's a finding about our
scaffold, and we want to hear it.
"""

from __future__ import annotations

import json
import os
import time
from pathlib import Path

DEFAULT_BUDGET = 100_000_000
FLUSH_EVERY = 50_000


class BudgetExhausted(RuntimeError):
    """Raised inside a worker once the step budget is spent."""


class StepBudget:
    """Counts steps in one process and appends periodic records to the log."""

    def __init__(self, log_path: str | os.PathLike, per_process_cap: int | None = None):
        self.log_path = Path(log_path)
        self.log_path.parent.mkdir(parents=True, exist_ok=True)
        self.per_process_cap = per_process_cap
        self.count = 0
        self._last_flush = 0

    def tick(self, n: int = 1) -> None:
        self.count += n
        if self.per_process_cap is not None and self.count >= self.per_process_cap:
            self.flush()
            raise BudgetExhausted(
                f"process {os.getpid()} reached its share of the step budget "
                f"({self.count:,} steps)"
            )
        if self.count - self._last_flush >= FLUSH_EVERY:
            self.flush()

    def flush(self) -> None:
        if self.count == self._last_flush:
            return
        record = {"pid": os.getpid(), "cum_steps": self.count, "wall_ts": time.time()}
        with self.log_path.open("a") as fh:
            fh.write(json.dumps(record) + "\n")
        self._last_flush = self.count


def total_steps(log_path: str | os.PathLike) -> int:
    """Sum the budget log: the latest cumulative count from each process."""
    path = Path(log_path)
    if not path.exists():
        return 0
    latest: dict[int, int] = {}
    with path.open() as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            latest[rec["pid"]] = max(latest.get(rec["pid"], 0), rec["cum_steps"])
    return sum(latest.values())


class BudgetedEnv:
    """Wraps an environment so every step is counted.

    Attribute access and return values pass straight through to the wrapped
    environment — this only counts.
    """

    def __init__(self, env, budget: StepBudget):
        self._env = env
        self._budget = budget

    def reset(self, *args, **kwargs):
        return self._env.reset(*args, **kwargs)

    def step(self, *args, **kwargs):
        self._budget.tick()
        return self._env.step(*args, **kwargs)

    def __getattr__(self, name):
        return getattr(self._env, name)
